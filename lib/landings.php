/** Лендинг по slug или null. */
function landing_get(string $slug): ?array
{
    $all = landings_data();
    return $all[$slug] ?? null;
}

/**
 * Инлайн-разметка в текстах: [[/path|текст]] — ссылка, **текст** — выделение.
 * Экранирование выполняется здесь, HTML в данные не попадает.
 */
function landing_inline(string $text): string
{
    $safe = e($text);
    $safe = (string) preg_replace_callback(
        '/\[\[(\/[a-z0-9\-\/]+)\|([^\]]+)\]\]/u',
        static fn(array $m): string => '<a href="' . e($m[1]) . '">' . $m[2] . '</a>',
        $safe
    );
    return (string) preg_replace('/\*\*([^*]+)\*\*/u', '<strong>$1</strong>', $safe);
}

/** Slug-и лендингов (для sitemap и проверок). */
function landings_slugs(): array
{
    return array_keys(landings_data());
}

