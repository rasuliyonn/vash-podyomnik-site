/** Возвращает оборудование по slug с учётом переопределений из БД (или null). */
function equipment_get(string $slug): ?array
{
    $static = equipment_static()[$slug] ?? null;
    if ($static === null) {
        return null;
    }

    $data = $static;
    $data['slug'] = $slug;
    $data['videoUrl'] = null;
    $data['visible'] = true;
    $data['images'] = [];
    $data['documents'] = [];

    try {
        $stmt = db()->prepare('SELECT * FROM equipment_types WHERE slug = :slug AND visible = 1 LIMIT 1');
        $stmt->execute([':slug' => $slug]);
        $row = $stmt->fetch();
    } catch (Throwable $e) {
        $row = false;
    }

    if ($row) {
        if (trim((string) $row['title']) !== '') $data['title'] = $row['title'];
        if (trim((string) $row['description']) !== '') $data['description'] = $row['description'];
        $features = json_decode((string) $row['features_json'], true);
        if (is_array($features) && $features) $data['features'] = array_values(array_filter(array_map('trim', $features)));
        $advantages = json_decode((string) $row['advantages_json'], true);
        if (is_array($advantages) && $advantages) $data['advantages'] = array_values(array_filter(array_map('trim', $advantages)));
        $applications = json_decode((string) $row['applications_json'], true);
        if (is_array($applications) && $applications) $data['applications'] = array_values(array_filter(array_map('trim', $applications)));
        $techSpecs = json_decode((string) $row['tech_specs_json'], true);
        if (is_array($techSpecs) && $techSpecs) {
            $clean = [];
            foreach ($techSpecs as $spec) {
                if (is_array($spec) && isset($spec['name'])) {
                    $clean[] = ['name' => (string) $spec['name'], 'value' => (string) ($spec['value'] ?? '')];
                }
            }
            if ($clean) $data['techSpecs'] = $clean;
        }
        $data['videoUrl'] = $row['video_url'] ?: null;

        $imgStmt = db()->prepare('SELECT id, url, caption FROM equipment_images WHERE equipment_id = :id ORDER BY sort_order ASC, id ASC');
        $imgStmt->execute([':id' => $row['id']]);
        $data['images'] = $imgStmt->fetchAll();

        $docStmt = db()->prepare('SELECT id, url, name, doc_type, size_kb FROM equipment_documents WHERE equipment_id = :id ORDER BY id ASC');
        $docStmt->execute([':id' => $row['id']]);
        $data['documents'] = $docStmt->fetchAll();
    }

    return $data;
}

/** Все типы оборудования (для каталога, sitemap и админки). Порядок фиксирован. */
function equipment_order(): array
{
    return ['shaftnye', 'konsolnye', 'servisnye', 'kottedzhnye', 'platformy'];
}

function equipment_all(): array
{
    $items = [];
    foreach (equipment_order() as $slug) {
        $data = equipment_get($slug);
        if ($data !== null) {
            $items[$slug] = $data;
        }
    }
    return $items;
}
